#!/usr/bin/env python3
"""Regenerate src/cloud_ranges.rs from the providers' public IP range lists.

    python3 tools/update_cloud_ranges.py            # download and regenerate
    python3 tools/update_cloud_ranges.py G.json A.json   # use local copies

Sources:
  Google Cloud: https://www.gstatic.com/ipranges/cloud.json
  AWS:          https://ip-ranges.amazonaws.com/ip-ranges.json
"""
import ipaddress
import json
import pathlib
import sys
import urllib.request

GCP_URL = "https://www.gstatic.com/ipranges/cloud.json"
AWS_URL = "https://ip-ranges.amazonaws.com/ip-ranges.json"
OUT = pathlib.Path(__file__).resolve().parent.parent / "src" / "cloud_ranges.rs"


def load(arg, url):
    if arg:
        return json.loads(pathlib.Path(arg).read_text())
    with urllib.request.urlopen(url, timeout=60) as r:
        return json.loads(r.read())


def collect(entries, region_key):
    """[(first, last, region)] for IPv4 prefixes, sorted and with adjacent same-region ranges merged."""
    rows = []
    for e in entries:
        p = e.get("ipv4Prefix") or e.get("ip_prefix")
        if not p:
            continue
        n = ipaddress.IPv4Network(p)
        rows.append((int(n.network_address), int(n.broadcast_address), e.get(region_key, "")))
    rows.sort()
    merged = []
    for lo, hi, reg in rows:
        if merged and lo <= merged[-1][1] + 1 and merged[-1][2] == reg:
            merged[-1][1] = max(merged[-1][1], hi)
        elif merged and hi <= merged[-1][1]:
            continue  # fully contained in the previous range
        else:
            merged.append([lo, hi, reg])
    return merged


def main():
    gcp = load(sys.argv[1] if len(sys.argv) > 1 else None, GCP_URL)
    aws = load(sys.argv[2] if len(sys.argv) > 2 else None, AWS_URL)
    g = collect(gcp["prefixes"], "scope")
    a = collect([p for p in aws["prefixes"] if p.get("service") == "AMAZON"], "region")
    regions = sorted({r for *_, r in g + a})
    idx = {r: i for i, r in enumerate(regions)}
    out = [
        "// @generated by tools/update_cloud_ranges.py — do not edit by hand.",
        f"// Google Cloud list: {gcp.get('creationTime', '?')}, AWS list: {aws.get('createDate', '?')}.",
        "",
        "/// Region names referenced by index from the range tables.",
        "pub const REGIONS: &[&str] = &[",
        *[f'    "{r}",' for r in regions],
        "];",
        "",
    ]
    for name, rows in (("GOOGLE_CLOUD", g), ("AWS", a)):
        out.append(f"/// {name} IPv4 ranges: (first, last, region index), sorted by first address.")
        out.append(f"pub const {name}: &[(u32, u32, u16)] = &[")
        out += [f"    (0x{lo:08x}, 0x{hi:08x}, {idx[r]})," for lo, hi, r in rows]
        out.append("];")
        out.append("")
    OUT.write_text("\n".join(out))
    print(f"wrote {OUT}: {len(g)} Google Cloud ranges, {len(a)} AWS ranges, {len(regions)} regions")


if __name__ == "__main__":
    main()
